import { useCallback, useEffect, useState } from "react";
import type { Spec } from "@json-render/core";
import { PageHeader, Card, Callout } from "@/components/shell/Primitives";
import { SpecRenderer } from "@/components/gemma/SpecRenderer";

interface SpecEntry {
  id: string;
  spec: Spec;
  prompt: string;
  tags: string[];
  created_at: number;
  signature: string;
}

interface Gallery {
  version: number;
  specs: SpecEntry[];
}

export default function GalleryPage() {
  const [specs, setSpecs] = useState<SpecEntry[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState<string | null>(null);

  const load = useCallback(async () => {
    try {
      const r = await fetch("/api/gemma/gallery");
      if (!r.ok) throw new Error(`gallery HTTP ${r.status}`);
      const g: Gallery = await r.json();
      setSpecs(g.specs ?? []);
      setError(null);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void load();
    const t = setInterval(() => void load(), 5000);
    return () => clearInterval(t);
  }, [load]);

  const promote = async (id: string) => {
    setBusy(id);
    try {
      const r = await fetch(`/api/gemma/catalog/promote/${id}`, { method: "POST" });
      if (!r.ok) throw new Error(`promote HTTP ${r.status}`);
      setSpecs((prev) => prev.filter((s) => s.id !== id));
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(null);
    }
  };

  const remove = async (id: string) => {
    setBusy(id);
    try {
      const r = await fetch(`/api/gemma/gallery/${id}`, { method: "DELETE" });
      if (!r.ok && r.status !== 204) throw new Error(`delete HTTP ${r.status}`);
      setSpecs((prev) => prev.filter((s) => s.id !== id));
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(null);
    }
  };

  return (
    <div className="space-y-4">
      <PageHeader
        title="Gemma Gallery"
        subtitle="Live json-render specs generated by Gemma from the sealed blob catalog. Promote moves a spec into the finalized catalog."
      />
      {error && <Callout variant="danger">{error}</Callout>}
      {loading && specs.length === 0 && (
        <div className="text-sm text-muted-foreground">Loading gallery…</div>
      )}
      {!loading && specs.length === 0 && !error && (
        <Callout variant="default">
          Gallery is empty. Run the op-gemma binary with Ollama available to
          generate specs.
        </Callout>
      )}
      <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-4">
        {specs.map((entry) => (
          <Card
            key={entry.id}
            title={entry.id}
            actions={
              <div className="flex gap-1.5">
                <button
                  disabled={busy === entry.id}
                  onClick={() => void promote(entry.id)}
                  className="px-2 py-1 text-[11px] rounded-md bg-primary text-primary-foreground hover:bg-primary/90 disabled:opacity-50"
                >
                  Promote
                </button>
                <button
                  disabled={busy === entry.id}
                  onClick={() => void remove(entry.id)}
                  className="px-2 py-1 text-[11px] rounded-md border border-border hover:bg-muted/30 disabled:opacity-50"
                >
                  Delete
                </button>
              </div>
            }
          >
            <div className="rounded-md border border-border bg-background/40 p-2 max-h-[360px] overflow-auto">
              <SpecRenderer spec={entry.spec} />
            </div>
            {entry.prompt && (
              <p className="mt-2 text-[11px] text-muted-foreground line-clamp-3">
                {entry.prompt}
              </p>
            )}
          </Card>
        ))}
      </div>
    </div>
  );
}
