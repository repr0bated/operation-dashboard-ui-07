#!/usr/bin/env node
/**
 * Scans src/grpc/gen/plugin_methods/*.client.ts and emits:
 *   - src/grpc/gen/plugin-methods-index.ts
 *
 * The index gives the UI:
 *   - a re-export of every generated *ServiceClient
 *   - a subid → { plugin, method, invoke(transport, input) } registry
 *   - a byPlugin(name) helper
 *
 * Re-run after `bun run proto:gen`.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const GEN_DIR = join(__dirname, "..", "src", "grpc", "gen", "plugin_methods");
const OUT = join(__dirname, "..", "src", "grpc", "gen", "plugin-methods-index.ts");

const files = readdirSync(GEN_DIR).filter((f) => f.endsWith(".client.ts"));

const entries = [];
for (const clientFile of files) {
  const base = clientFile.replace(/\.client\.ts$/, "");
  const clientSrc = readFileSync(join(GEN_DIR, clientFile), "utf8");
  const typeSrc = readFileSync(join(GEN_DIR, `${base}.ts`), "utf8");

  // Client class name, e.g. `export class SetModelServiceClient implements ...`
  const clientClass = clientSrc.match(/export class (\w+ServiceClient)\b/)?.[1];
  // Service class it wraps (for typeName lookup) — imported from base
  const serviceClass = clientSrc.match(/import \{ (\w+Service) \} from "\.\//)?.[1];
  // The rpc method name on the client
  const methodName = clientSrc.match(/@generated from protobuf rpc: \w+\s*\*\/\s*\n\s*(\w+)\(input:/)?.[1]
    ?? clientSrc.match(/\n\s{4}(\w+)\(input:[^)]+\):\s*UnaryCall/)?.[1];
  // Input/Output type names
  const inputType = clientSrc.match(/import type \{ (\w+Input) \}/)?.[1];
  const outputType = clientSrc.match(/import type \{ (\w+Output) \}/)?.[1];
  // Service typeName (fully qualified), from the types file: super("pkg.Service", ...)
  const typeName = typeSrc.match(/super\("([^"]+)",\s*\[/g)
    ? (typeSrc.match(/new ServiceType\("([^"]+)"/)?.[1]
      ?? typeSrc.match(/typeName\s*=\s*"([^"]+)"/)?.[1])
    : null;
  // ServiceType is typically declared as `export const XService = new ServiceType("pkg.Service", ...)`
  const svcTypeName = typeSrc.match(/new ServiceType\("([^"]+)"/)?.[1];
  // subid from the doc comment
  const subid = clientSrc.match(/subid:\s*([^\s,]+)/)?.[1] ?? null;
  const capability = clientSrc.match(/capability:\s*([^\s*]+)/)?.[1] ?? null;

  // plugin name = first token before "__"
  const plugin = base.split("__")[0];

  if (!clientClass || !methodName || !inputType || !outputType || !svcTypeName) {
    console.warn("[skip]", clientFile, { clientClass, methodName, inputType, outputType, svcTypeName });
    continue;
  }

  entries.push({
    base,
    plugin,
    clientClass,
    serviceClass,
    methodName,
    inputType,
    outputType,
    typeName: svcTypeName,
    subid,
    capability,
  });
}

entries.sort((a, b) => a.base.localeCompare(b.base));

const lines = [];
lines.push("/* eslint-disable */");
lines.push("// AUTO-GENERATED by scripts/gen-plugin-methods-index.mjs — do not edit.");
lines.push("// Re-run after `bun run proto:gen`.");
lines.push("");
lines.push('import type { RpcTransport, UnaryCall } from "@protobuf-ts/runtime-rpc";');
lines.push("");

// Imports
for (const e of entries) {
  lines.push(`import { ${e.clientClass} } from "./plugin_methods/${e.base}.client";`);
  lines.push(`import type { ${e.inputType}, ${e.outputType} } from "./plugin_methods/${e.base}";`);
}
lines.push("");

// Re-exports
lines.push("export {");
for (const e of entries) lines.push(`  ${e.clientClass},`);
lines.push("};");
lines.push("");

// Registry entry type
lines.push(`export interface PluginMethodEntry {
  plugin: string;
  method: string;
  typeName: string;
  subid: string | null;
  capability: string | null;
  invoke(transport: RpcTransport, input: any, options?: any): UnaryCall<any, any>;
}`);
lines.push("");

lines.push("export const PLUGIN_METHOD_ENTRIES: readonly PluginMethodEntry[] = [");
for (const e of entries) {
  lines.push(`  { plugin: ${JSON.stringify(e.plugin)}, method: ${JSON.stringify(e.methodName)}, typeName: ${JSON.stringify(e.typeName)}, subid: ${JSON.stringify(e.subid)}, capability: ${JSON.stringify(e.capability)}, invoke: (t, i, o) => new ${e.clientClass}(t).${e.methodName}(i, o) },`);
}
lines.push("] as const;");
lines.push("");

// Indexes
lines.push(`const _bySubid = new Map<string, PluginMethodEntry>();
const _byTypeName = new Map<string, PluginMethodEntry>();
const _byPlugin = new Map<string, PluginMethodEntry[]>();
for (const e of PLUGIN_METHOD_ENTRIES) {
  if (e.subid) _bySubid.set(e.subid, e);
  _byTypeName.set(e.typeName + "/" + e.method, e);
  const arr = _byPlugin.get(e.plugin) ?? [];
  arr.push(e);
  _byPlugin.set(e.plugin, arr);
}

export const PLUGIN_METHOD_BY_SUBID: ReadonlyMap<string, PluginMethodEntry> = _bySubid;
export const PLUGIN_METHOD_BY_TYPENAME: ReadonlyMap<string, PluginMethodEntry> = _byTypeName;
export const PLUGIN_METHOD_BY_PLUGIN: ReadonlyMap<string, readonly PluginMethodEntry[]> = _byPlugin;
`);

writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`wrote ${OUT} — ${entries.length} entries`);
